// Values below are drawn from the 2024 Adult Compendium of Physical
// Activities (Herrmann et al., Journal of Sport and Health Science,
// 2024 — the current peer-reviewed standard, superseding the 2011
// edition), narrowed to recreational/everyday activities a general
// fitness app user would actually look up, with wattage- and
// cadence-specific gym-equipment variants excluded in favor of their
// speed/effort-described equivalents.
