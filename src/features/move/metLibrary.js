// ACSM's standard three-tier intensity classification, matching the
// Light / Moderate / Vigorous split used everywhere else in Groove.
export function metIntensity(met) {
  if (met < 3) return 'Light';
  if (met <= 6) return 'Moderate';
  return 'Vigorous';
}

